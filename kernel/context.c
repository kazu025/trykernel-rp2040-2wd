/**
 * @file    context.c
 * @brief   タスクの初期実行コンテキストを作成する。
 *
 * @details
 * TryKernelのタスク切替で使用するスタック上のコンテキスト情報を
 * 管理する。
 *
 * タスク生成時に、タスクスタックの末尾へ初期スタックフレームを
 * 作成する。ディスパッチャはこのスタックフレームを復元することで、
 * 新しく生成されたタスクを実行開始できる。
 *
 * 本ファイルでは、Cortex-Mプロセッサのコンテキスト切替で使用する
 * 保存レジスタ領域と、タスク開始用の初期コンテキストを作成する
 * make_context()を定義する。
 *
 * @note
 * コンテキストを作成するスタック領域は、呼び出し元が確保して
 * 渡す必要がある。
 *
 * @note
 * 初期コンテキストのPCにはタスク開始関数のアドレスを設定し、
 * xPSRにはThumb状態を示す値を設定する。
 * --------------------------------------------------
 * タスク生成
 *     ↓
 * make_context()
 *     ↓
 * タスクスタック上に初期StackFrameを作成
 *     ↓
 * TCBへコンテキストポインタを保存
 *     ↓
 * dispatch_entry()がフレームを復元
 *     ↓
 * タスク開始関数を実行
 * --------------------------------------------------
 */

#include <typedef.h>
#include <sysdef.h>
#include <syslib.h>
#include <knldef.h>

/**
 * @brief スタック上に保存されるタスクの実行コンテキスト。
 *
 * @details
 * コンテキスト切替時にスタックへ保存されるレジスタ情報を表す。
 * R4～R11はディスパッチャがソフトウェアで退避し、
 * R0～R3、R12、LR、PC、xPSRは例外処理により保存される。
 *
 * ディスパッチャは、この構造体に保存された値を復元することで、
 * タスクの実行を再開する。
 */
typedef struct {
    /** R4～R11レジスタの保存領域。 */
    UW r_[8];

    /** R0～R3レジスタの保存領域。 */
    UW r[4];

    /** R12レジスタの保存値。 */
    UW ip;

    /** LR（リンクレジスタ）の保存値。 */
    UW lr;

    /** PC（プログラムカウンタ）の保存値。 */
    UW pc;

    /** xPSR（プログラムステータスレジスタ）の保存値。 */
    UW xpsr;
} StackFrame;

/**
 * @brief タスクの初期実行コンテキストを作成する。
 *
 * @details
 * 指定されたスタック領域の末尾に初期スタックフレームを確保し、
 * タスク開始時に必要なxPSRおよびPCの初期値を設定する。
 *
 * xPSRにはThumb状態を示す値（0x01000000）を設定し、
 * PCにはタスク開始関数のアドレスを設定する。
 *
 * 作成したコンテキストへのポインタは、タスク管理ブロックに保存され、
 * ディスパッチャによるコンテキスト復元時に使用される。
 *
 * @param[in] sp   タスク用スタック領域の先頭アドレス。
 * @param[in] ssize タスク用スタック領域のサイズ（バイト）。
 * @param[in] fp   タスク開始時に実行する関数のアドレス。
 *
 * @return void* 作成した初期スタックフレームへのポインタ。
 *
 * @note
 * spが示す領域には、初期スタックフレームを格納できる十分な
 * サイズが必要である。
 */
void *make_context(UW *sp, UINT ssize, void (*fp)())
{
    StackFrame	*sfp;

    /* スタック上の実行コンテクスト情報へのポインタをsfpに設定 */
    sfp = (StackFrame*)((UW)sp + ssize);
    sfp--;

    /* 実行コンテキスト情報の初期化 */
    sfp->xpsr       = 0x01000000;
    sfp->pc         = (UW)fp & ~0x00000001UL;

    return (void*)sfp;
}
